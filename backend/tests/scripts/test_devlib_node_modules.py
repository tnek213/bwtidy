import json
from pathlib import Path

import pytest
from devlib import locks

PROJECT = Path("frontend")


def write_lock(root: Path, version: str) -> None:
    lock = {"packages": {"": {}, "node_modules/x": {"version": version}}}
    (root / PROJECT / "package-lock.json").write_text(json.dumps(lock))


@pytest.fixture
def root(tmp_path):
    (tmp_path / PROJECT).mkdir()
    write_lock(tmp_path, "1.0.0")
    return tmp_path


def installed(root: Path) -> None:
    (root / PROJECT / "node_modules").mkdir()
    locks.write_npm_stamp(PROJECT, root)


def test_no_node_modules_means_install(root):
    assert locks.npm_install_needed(PROJECT, root)


def test_matching_node_modules_means_no_install(root):
    installed(root)
    assert not locks.npm_install_needed(PROJECT, root)


def test_changed_lock_for_node_modules_means_install(root):
    installed(root)
    write_lock(root, "1.0.1")
    assert locks.npm_install_needed(PROJECT, root)


def test_node_modules_without_stamp_means_install(root):
    (root / PROJECT / "node_modules").mkdir()
    assert locks.npm_install_needed(PROJECT, root)
