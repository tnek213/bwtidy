import json
from email.message import Message
from importlib import metadata

import pytest
from devlib import load_script

third_party = load_script("third-party")

LOCK = {
    "lockfileVersion": 3,
    "packages": {
        "": {"name": "bwtidy-frontend", "version": "0.1.0-alpha.1", "license": "AGPL-3.0-only"},
        "node_modules/react": {"version": "19.3.1", "license": "MIT"},
        "node_modules/scheduler": {"version": "0.28.0", "license": "MIT"},
        "node_modules/vite": {"version": "8.3.4", "license": "MIT", "dev": True},
        "node_modules/prop-types/node_modules/react-is": {"version": "16.13.1", "license": "MIT"},
    },
}

EXPORT = """\
# This file was autogenerated by uv via the following command:
fastapi==0.162.0
    # via bwtidy
starlette==1.10.0
pyrage==1.4.0
pywin32==312 ; sys_platform == 'win32'
"""


def meta(**fields: str | list[str]) -> Message:
    message = Message()
    for key, value in fields.items():
        for one in value if isinstance(value, list) else [value]:
            message[key.replace("_", "-")] = one
    return message


def reader(starlette: Message):
    """A stub of importlib.metadata.metadata with three packages installed."""
    installed = {
        "fastapi": meta(License_Expression="MIT"),
        "starlette": starlette,
        "pyrage": meta(),
    }

    def read(name: str) -> Message:
        if name not in installed:
            raise metadata.PackageNotFoundError(name)
        return installed[name]

    return read


def test_npm_leaves_out_the_root_and_the_dev_packages():
    found = third_party.npm_packages(LOCK, {"react"})
    assert [(p["name"], p["version"]) for p in found] == [
        ("react", "19.3.1"),
        ("scheduler", "0.28.0"),
        ("react-is", "16.13.1"),
    ]
    assert all(p["ecosystem"] == "npm" and p["license"] == "MIT" for p in found)


def test_direct_marks_only_the_named_dependencies():
    found = third_party.npm_packages(LOCK, {"react"})
    assert {p["name"]: p["direct"] for p in found} == {
        "react": True,
        "scheduler": False,
        "react-is": False,
    }


def test_an_npm_package_without_a_license_names_it():
    lock = {"packages": {"node_modules/odd": {"version": "1.0.0"}}}
    with pytest.raises(ValueError, match="odd"):
        third_party.npm_packages(lock, set())


def test_pypi_reads_the_expression_the_classifier_and_the_overrides():
    starlette = meta(Classifier=["License :: OSI Approved :: MIT License", "Typing :: Typed"])
    found = third_party.pypi_packages(EXPORT, {"fastapi", "pyrage"}, reader(starlette))
    assert found == [
        {
            "name": "fastapi",
            "version": "0.162.0",
            "ecosystem": "PyPI",
            "license": "MIT",
            "direct": True,
        },
        {
            "name": "starlette",
            "version": "1.10.0",
            "ecosystem": "PyPI",
            "license": "MIT",
            "direct": False,
        },
        {
            "name": "pyrage",
            "version": "1.4.0",
            "ecosystem": "PyPI",
            "license": "MIT",
            "direct": True,
        },
    ]


def test_a_classifier_that_names_no_one_license_raises_with_the_name():
    starlette = meta(Classifier="License :: OSI Approved :: BSD License")
    with pytest.raises(ValueError, match="starlette"):
        third_party.pypi_packages(EXPORT, set(), reader(starlette))


def test_a_package_without_license_metadata_or_override_raises_with_the_name(monkeypatch):
    monkeypatch.setattr(third_party, "OVERRIDES", {})
    starlette = meta(License_Expression="BSD-3-Clause")
    with pytest.raises(ValueError, match="pyrage"):
        third_party.pypi_packages(EXPORT, set(), reader(starlette))


def test_a_missing_package_without_a_marker_is_an_error():
    with pytest.raises(metadata.PackageNotFoundError):
        third_party.pypi_packages("absent==1.0\n", set(), reader(meta()))


def test_the_direct_dependencies_come_from_package_json_and_pyproject():
    assert third_party.pypi_direct() == {
        "cryptography",
        "fastapi",
        "httpx2",
        "mcp",
        "pyrage",
        "uvicorn",
    }
    assert "react" in third_party.npm_direct()


def test_stale_names_names_what_differs():
    old = [{"name": "a", "version": "1"}, {"name": "b", "version": "1"}]
    new = [{"name": "a", "version": "2"}, {"name": "b", "version": "1"}, {"name": "c"}]
    assert third_party.stale_names(old, new) == ["a", "c"]


def test_the_committed_list_is_up_to_date():
    committed = json.loads(third_party.OUTPUT.read_text())
    assert third_party.stale_names(committed, third_party.collect()) == []
